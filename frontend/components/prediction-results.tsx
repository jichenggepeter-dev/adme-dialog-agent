"use client";

import { CATEGORY_ORDER } from "@/lib/constants";
import type { EndpointMetadata, PredictionResponse } from "@/lib/types";
import { useState } from "react";
import { ExportActions } from "./export-actions";
import { PredictionCategory } from "./prediction-category";
import { RawOutputPanel } from "./raw-output-panel";

export function PredictionResults({ result, endpointRegistry = {}, highlightedCategory, onCategoryElement }: { result: PredictionResponse; endpointRegistry?: Record<string, EndpointMetadata>; highlightedCategory?: string | null; onCategoryElement?: (category: string, element: HTMLElement | null) => void }) {
  const [showAll, setShowAll] = useState(false);
  const populated = CATEGORY_ORDER.filter((category) => Object.keys(result.predictions[category]).length > 0);
  const total = populated.reduce((count, category) => count + Object.keys(result.predictions[category]).length, 0);
  const previewKeys = (() => {
    const selected = Object.fromEntries(populated.map((category) => [category, [] as string[]])) as Record<string, string[]>;
    const queues = Object.fromEntries(populated.map((category) => [category, Object.keys(result.predictions[category])])) as Record<string, string[]>;
    while (Object.values(selected).reduce((count, keys) => count + keys.length, 0) < Math.min(10, total)) {
      let added = false;
      for (const category of populated) {
        const next = queues[category].shift(); if (!next) continue;
        selected[category].push(next); added = true;
        if (Object.values(selected).reduce((count, keys) => count + keys.length, 0) >= Math.min(10, total)) break;
      }
      if (!added) break;
    }
    return selected;
  })();
  return (
    <div className="prediction-results" aria-live="polite">
      {result.prediction_mode === "mock" ? <div className="mock-warning" role="status"><strong>Development mode:</strong> results are deterministic mock data and were not generated by the real ADMET-AI model.</div> : null}
      <section className="computational-summary" aria-labelledby="summary-heading">
        <h2 id="summary-heading">Computational Summary</h2>
        <p>{result.summary}</p>
        <div className="prediction-table-groups">
          {populated.map((category) => {
            const allValues = result.predictions[category];
            const visibleValues = showAll ? allValues : Object.fromEntries((previewKeys[category] ?? []).map((key) => [key, allValues[key]]));
            if (!Object.keys(visibleValues).length) return null;
            return <PredictionCategory key={category} category={category} values={visibleValues} totalCount={Object.keys(allValues).length} endpointRegistry={endpointRegistry} highlighted={highlightedCategory === category} sectionRef={(element) => onCategoryElement?.(category, element)} />;
          })}
        </div>
        {total > 10 ? <div className="prediction-disclosure"><span>Showing {showAll ? total : 10} of {total} endpoints</span><button className="secondary-action" onClick={() => setShowAll((value) => !value)}>{showAll ? "Show first 10" : `See ${total - 10} more`}</button></div> : null}
      </section>
      <ExportActions result={result} />
      <RawOutputPanel result={result} />
      <div className="result-disclaimer"><strong>Scientific use notice.</strong> These results are computational predictions and not experimental measurements. They should not be used as clinical, regulatory, or definitive safety conclusions.</div>
    </div>
  );
}
